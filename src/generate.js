// robots.txt generator.
import registry from './crawlers-data.js';
import { parseRobots, byteLength } from './robots.js';
import { GENERATE_NOTE } from './personal-agents.js';

export const CATEGORIES = Object.keys(registry.categories);
export const LIMITS = { maxAgents: 100, maxPaths: 100, maxPathLen: 512, maxSitemaps: 20, maxCustomBytes: 20000 };
const ACTIONS = new Set(['allow', 'block', 'omit']);
const TOKEN_RE = /^[A-Za-z0-9_.-]{1,64}$/;

export class InputError extends Error {
  constructor(message, details) {
    super(message);
    this.details = details;
  }
}

/**
 * input: {
 *   categories?: { training?: 'allow'|'block'|'omit', dataset?, search?, user_fetch?, other? },
 *   agents?: { [token]: 'allow'|'block'|'omit' },   // overrides; custom tokens allowed
 *   default?: 'allow'|'block',                         // User-agent: * policy (default allow)
 *   disallow_paths?: string[], allow_paths?: string[], // applied to * and to explicitly allowed AI groups
 *   sitemaps?: string[] | sitemap?: string,
 *   custom_rules?: string,                             // appended verbatim after validation
 *   date?: string
 * }
 */
export function generateRobots(input = {}) {
  if (input === null || typeof input !== 'object' || Array.isArray(input)) throw new InputError('Body must be a JSON object.');
  const problems = [];

  const categories = input.categories ?? {};
  if (typeof categories !== 'object' || Array.isArray(categories)) problems.push('categories must be an object');
  for (const [k, v] of Object.entries(categories || {})) {
    if (!CATEGORIES.includes(k)) problems.push(`unknown category "${k}" (valid: ${CATEGORIES.join(', ')})`);
    if (!ACTIONS.has(v)) problems.push(`categories.${k} must be one of allow, block, omit`);
  }
  const agents = input.agents ?? {};
  if (typeof agents !== 'object' || Array.isArray(agents)) problems.push('agents must be an object');
  const agentEntries = Object.entries(agents || {});
  if (agentEntries.length > LIMITS.maxAgents) problems.push(`at most ${LIMITS.maxAgents} agents`);
  for (const [k, v] of agentEntries) {
    if (!TOKEN_RE.test(k) || k === '*') problems.push(`agent token "${String(k).slice(0, 64)}" is invalid (letters, digits, _ . - only)`);
    if (!ACTIONS.has(v)) problems.push(`agents.${k} must be one of allow, block, omit`);
  }
  const def = input.default ?? 'allow';
  if (def !== 'allow' && def !== 'block') problems.push('default must be "allow" or "block"');

  const disallowPaths = checkPaths(input.disallow_paths, 'disallow_paths', problems);
  const allowPaths = checkPaths(input.allow_paths, 'allow_paths', problems);

  let sitemaps = input.sitemaps ?? (input.sitemap ? [input.sitemap] : []);
  if (!Array.isArray(sitemaps)) problems.push('sitemaps must be an array of URLs');
  else {
    if (sitemaps.length > LIMITS.maxSitemaps) problems.push(`at most ${LIMITS.maxSitemaps} sitemaps`);
    sitemaps.forEach((s) => {
      if (typeof s !== 'string' || s.length > 2048 || /\s/.test(s)) return problems.push('each sitemap must be a URL string without spaces');
      try {
        const u = new URL(s);
        if (u.protocol !== 'http:' && u.protocol !== 'https:') problems.push(`sitemap "${s.slice(0, 100)}" must be http(s)`);
      } catch {
        problems.push(`sitemap "${s.slice(0, 100)}" is not a valid absolute URL`);
      }
    });
  }

  const custom = input.custom_rules ?? '';
  if (typeof custom !== 'string') problems.push('custom_rules must be a string');
  else if (byteLength(custom) > LIMITS.maxCustomBytes) problems.push(`custom_rules exceeds ${LIMITS.maxCustomBytes} bytes`);

  if (problems.length) throw new InputError('Invalid generate request.', problems);

  // Resolve action per registry crawler.
  const decided = new Map(); // lowerName -> {name, action, source}
  for (const c of registry.crawlers) {
    const a = categories[c.category];
    if (a) decided.set(c.name.toLowerCase(), { name: c.name, action: a, source: `category:${c.category}`, crawler: c });
  }
  for (const [tok, a] of agentEntries) {
    const c = registry.crawlers.find((x) => x.name.toLowerCase() === tok.toLowerCase());
    decided.set(tok.toLowerCase(), { name: c ? c.name : tok, action: a, source: 'agent', crawler: c || null });
  }

  const blocked = [...decided.values()].filter((d) => d.action === 'block');
  const allowed = [...decided.values()].filter((d) => d.action === 'allow');
  const date = typeof input.date === 'string' && /^\d{4}-\d{2}-\d{2}$/.test(input.date) ? input.date : new Date().toISOString().slice(0, 10);

  const out = [];
  out.push(`# robots.txt generated by RobotsGate on ${date}`);
  out.push('# Note: robots.txt is a voluntary standard (RFC 9309). Well-behaved crawlers follow it;');
  out.push('# it does not technically prevent access. Some user-triggered fetchers say they may ignore it.');
  out.push('');

  const notes = [];
  if (blocked.length) {
    out.push('# AI crawlers asked not to crawl this site');
    blocked.forEach((d) => out.push(`User-agent: ${d.name}`));
    out.push('Disallow: /');
    out.push('');
    blocked.filter((d) => d.crawler?.respects_robots === 'no_user_triggered').forEach((d) =>
      notes.push(`${d.name} is a user-triggered fetcher; ${d.crawler.operator} says it may not follow robots.txt.`));
    blocked.filter((d) => !d.crawler).forEach((d) => notes.push(`${d.name} is not in the RobotsGate registry; check the operator's docs for the correct token.`));
  }
  if (allowed.length) {
    out.push('# AI crawlers explicitly allowed (named groups replace the "*" group, so shared path rules are repeated here)');
    allowed.forEach((d) => out.push(`User-agent: ${d.name}`));
    allowPaths.forEach((p) => out.push(`Allow: ${p}`));
    disallowPaths.forEach((p) => out.push(`Disallow: ${p}`));
    if (!allowPaths.length && !disallowPaths.length) out.push('Allow: /');
    out.push('');
    allowed.filter((d) => !d.crawler).forEach((d) => notes.push(`${d.name} is not in the RobotsGate registry; check the operator's docs for the correct token.`));
  }

  out.push('# All other crawlers');
  out.push('User-agent: *');
  if (def === 'block') {
    out.push('Disallow: /');
    notes.push('default is "block": all crawlers not named above (including search engines like Googlebot) are asked not to crawl.');
  } else {
    allowPaths.forEach((p) => out.push(`Allow: ${p}`));
    disallowPaths.forEach((p) => out.push(`Disallow: ${p}`));
    if (!allowPaths.length && !disallowPaths.length) out.push('Allow: /');
  }

  const customTrim = custom.trim();
  let customDiagnostics = null;
  if (customTrim) {
    const p = parseRobots(customTrim);
    customDiagnostics = { errors: p.errors, warnings: p.warnings };
    out.push('');
    out.push('# Custom rules');
    out.push(customTrim);
  }

  if (Array.isArray(sitemaps) && sitemaps.length) {
    out.push('');
    sitemaps.forEach((s) => out.push(`Sitemap: ${s}`));
  }

  const robots = out.join('\n') + '\n';
  return {
    robots_txt: robots,
    summary: [...decided.values()].map((d) => ({ name: d.name, action: d.action, source: d.source, in_registry: !!d.crawler })),
    notes,
    custom_rules_diagnostics: customDiagnostics,
    // v0.2.7 (additive): robots.txt can't target personal agents such as Meta's Muse.
    personal_agents_note: GENERATE_NOTE,
  };
}

function checkPaths(v, field, problems) {
  if (v === undefined || v === null) return [];
  if (!Array.isArray(v)) {
    problems.push(`${field} must be an array of paths`);
    return [];
  }
  if (v.length > LIMITS.maxPaths) problems.push(`${field}: at most ${LIMITS.maxPaths} paths`);
  const ok = [];
  v.forEach((p) => {
    if (typeof p !== 'string' || p.length === 0 || p.length > LIMITS.maxPathLen) return problems.push(`${field}: each path must be a non-empty string up to ${LIMITS.maxPathLen} chars`);
    if (!p.startsWith('/') && !p.startsWith('*')) return problems.push(`${field}: "${p.slice(0, 80)}" must start with "/" or "*"`);
    if (/[\r\n#]/.test(p) || /\s/.test(p)) return problems.push(`${field}: "${p.slice(0, 80)}" must not contain whitespace, newlines or "#"`);
    ok.push(p);
  });
  return ok;
}
